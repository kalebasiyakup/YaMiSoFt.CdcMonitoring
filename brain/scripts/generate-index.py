#!/usr/bin/env python3
"""generate-index — INDEX.md katalogunu sayfaların frontmatter'ından üretir.

Elle tutulan bir indeks sessizce sapar: indekse girmemiş sayfa sorguda yok
demektir, ve bu hiçbir denetime yakalanmaz (başka bir sayfadan bağlantı aldığı
için yetim de sayılmaz). Katalog üretilirse sapma imkansız hale gelir.

Yalnız `<!-- index:start -->` ve `<!-- index:end -->` arasını yazar; dosyanın
elle yazılmış kalanına dokunmaz. Bağımlılık yok, ağ yok.

    py -3 scripts/generate-index.py .
    py -3 scripts/generate-index.py . --check      # fark varsa 1 ile çıkar
    py -3 scripts/generate-index.py . --dry-run    # ekrana yaz, dosyaya dokunma
"""

from __future__ import annotations

import argparse
import os
import re
import sys

START = "<!-- index:start -->"
END = "<!-- index:end -->"
NOTICE = "<!-- This section is generated by scripts/generate-index.py. Do not edit by hand. -->"

TYPE_SECTION = {
    "source": "Sources",
    "entity": "Entities",
    "concept": "Concepts",
    "decision": "Decisions",
    "analysis": "Analyses",
    "architecture": "Architecture",
}

ORDER = ["Overview", "Sources", "Entities", "Concepts",
         "Decisions", "Analyses", "Architecture", "Archive", "Unclassified"]

# Bu üçü katalog girdisi değil, katalogun kendisi ya da klasör işaretçisi.
SKIP_NAMES = {"index.md", "log.md", "readme.md"}


def parse_frontmatter(text: str) -> dict:
    lines = text.splitlines()
    if not lines or lines[0].strip() != "---":
        return {}
    fm: dict[str, str] = {}
    for line in lines[1:]:
        if line.strip() == "---":
            break
        m = re.match(r"^([A-Za-z_][\w-]*)\s*:\s*(.*)$", line)
        if m:
            fm[m.group(1)] = m.group(2).strip().strip("'\"")
    return fm


def first_heading(text: str) -> str:
    for line in text.splitlines():
        if line.startswith("# "):
            return line[2:].strip()
    return ""


def section_for(rel: str, fm: dict) -> str:
    if rel.startswith("wiki/archive/"):
        return "Archive"
    if rel == "wiki/overview.md":
        return "Overview"
    return TYPE_SECTION.get((fm.get("type") or "").strip().lower(), "Unclassified")


def collect(vault: str, wiki: str):
    pages, missing_summary = [], []
    root = os.path.join(vault, wiki)
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = [d for d in dirnames if not d.startswith(".")]
        for fn in sorted(filenames):
            if not fn.endswith(".md") or fn.lower() in SKIP_NAMES:
                continue
            full = os.path.join(dirpath, fn)
            rel = os.path.relpath(full, vault).replace(os.sep, "/")
            try:
                text = open(full, encoding="utf-8", errors="replace").read()
            except OSError:
                continue
            fm = parse_frontmatter(text)
            summary = (fm.get("summary") or "").strip()
            if not summary:
                missing_summary.append(rel)
                summary = "**no summary** (add `summary` to the frontmatter)"
            pages.append({
                "rel": rel,
                "slug": fn[:-3],
                "title": first_heading(text) or fn[:-3],
                "summary": summary,
                "date": (fm.get("date") or "").strip(),
                "status": (fm.get("status") or "").strip().lower(),
                "section": section_for(rel, fm),
            })
    return pages, missing_summary


def build_block(pages: list) -> str:
    out = [START, NOTICE, ""]
    by_section: dict[str, list] = {}
    for p in pages:
        by_section.setdefault(p["section"], []).append(p)

    for name in ORDER:
        items = by_section.get(name, [])
        if not items and name in ("Archive", "Unclassified"):
            continue
        out.append("## %s" % name)
        out.append("")
        if not items:
            out.append("*none yet*")
            out.append("")
            continue
        if name == "Decisions":
            items.sort(key=lambda p: (p["date"], p["slug"]), reverse=True)
        else:
            items.sort(key=lambda p: p["slug"])
        for p in items:
            marker = " `(deprecated)`" if p["status"] == "deprecated" else ""
            out.append("- [[%s]]%s — %s" % (p["slug"], marker, p["summary"]))
        out.append("")

    extra = [s for s in by_section if s not in ORDER]
    for name in sorted(extra):
        out.append("## %s" % name)
        out.append("")
        for p in sorted(by_section[name], key=lambda p: p["slug"]):
            out.append("- [[%s]] — %s" % (p["slug"], p["summary"]))
        out.append("")

    out.append(END)
    return "\n".join(out)


def splice(current: str, block: str) -> str:
    i, j = current.find(START), current.find(END)
    if i == -1 or j == -1 or j < i:
        raise SystemExit(
            "generate-index: markers %s / %s not found in INDEX.md.\n"
            "Put the catalog section between those two lines, then run again." % (START, END))
    return current[:i] + block + current[j + len(END):]


def main() -> int:
    for stream in (sys.stdout, sys.stderr):
        try:
            stream.reconfigure(encoding="utf-8", errors="replace")
        except (AttributeError, ValueError):
            pass

    p = argparse.ArgumentParser(description="Generates the INDEX.md catalog from frontmatter.")
    p.add_argument("vault", nargs="?", default=".", help="vault root")
    p.add_argument("--wiki", default="wiki", help="wiki folder (default: wiki)")
    p.add_argument("--index", default="INDEX.md", help="catalog file (default: INDEX.md)")
    p.add_argument("--check", action="store_true",
                   help="do not write; exit 1 if the file differs from the generated one (for pre-commit and CI)")
    p.add_argument("--dry-run", action="store_true", help="print the generated section")
    args = p.parse_args()

    vault = os.path.abspath(args.vault)
    index_path = os.path.join(vault, args.index)
    if not os.path.isdir(os.path.join(vault, args.wiki)):
        print("generate-index: wiki folder not found: %s" % os.path.join(vault, args.wiki),
              file=sys.stderr)
        return 2
    if not os.path.isfile(index_path):
        print("generate-index: catalog file not found: %s" % index_path, file=sys.stderr)
        return 2

    pages, missing_summary = collect(vault, args.wiki)
    block = build_block(pages)

    if args.dry_run:
        print(block)
        return 0

    current = open(index_path, encoding="utf-8").read()
    updated_text = splice(current, block)

    if args.check:
        if updated_text != current:
            print("generate-index: %s is out of date. Run: "
                  "py -3 scripts/generate-index.py ." % args.index, file=sys.stderr)
            return 1
        print("generate-index: %s is up to date (%d pages)" % (args.index, len(pages)))
        return 0

    if updated_text != current:
        with open(index_path, "w", encoding="utf-8", newline="") as fh:
            fh.write(updated_text)
        print("generate-index: %s written (%d pages)" % (args.index, len(pages)))
    else:
        print("generate-index: no changes (%d pages)" % len(pages))

    if missing_summary:
        print("\nsummary missing (%d pages):" % len(missing_summary), file=sys.stderr)
        for rel in missing_summary:
            print("  %s" % rel, file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
